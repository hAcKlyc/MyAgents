import assert from 'node:assert/strict';
import {writeFile} from 'node:fs/promises';
import {chromium} from 'playwright';
const out=import.meta.dirname;
const browser=await chromium.launch({headless:true,...(process.env.BOARD_BROWSER_EXECUTABLE?{executablePath:process.env.BOARD_BROWSER_EXECUTABLE}:{})});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const old='[data-board-row="task:task-done"]',retry='[data-board-row="task:task-retry"]';
const results=[];
const card=selector=>page.locator('article').filter({has:page.locator(selector)});
const listRow=selector=>page.locator('tr').filter({hasText:selector===old?'检查薪资前端构建及新测试服务器状态（合成）':'薪资管理恢复重试（合成）'});
for(const theme of ['light','dark']) {
 await page.goto('http://127.0.0.1:8889/__board_dedup'+(theme==='dark'?'?dark':''));
 await page.waitForSelector('[data-group="done"] '+old);
 await page.waitForSelector('[data-group="running"] '+retry);
 assert.doesNotMatch(await card(old).innerText(),/3\/21|本轮已用/);
 await card(retry).getByText('TODO 已完成 3/21',{exact:true}).waitFor();
 await page.screenshot({path:`${out}/${theme}.png`,fullPage:true});
 results.push(theme+': only retry shows live progress and completed check stays done');
}
await page.getByRole('button',{name:'列表',exact:true}).click();
assert.doesNotMatch(await listRow(old).innerText(),/3\/21|本轮已用/);
await listRow(retry).getByText('TODO 已完成 3/21',{exact:true}).waitFor();
results.push('list keeps one live progress presentation');
await page.getByRole('button',{name:'看板',exact:true}).click();
await card(old).locator('.pb-enter-session').click();
assert.equal(await page.evaluate(()=>window.boardCalls.filter(c=>c.kind==='openSession').at(-1).sessionId),'alpha-2');
await page.getByRole('button',{name:'项目看板',exact:true}).click();
results.push('completed check still opens the original shared Session');
await page.setViewportSize({width:540,height:900});
await card(retry).getByRole('button',{name:/^详情/}).click();
await page.getByRole('button',{name:'关闭详情',exact:true}).waitFor();
assert.match(await page.getByRole('complementary').innerText(),/Execution timed out/);
await page.keyboard.press('Escape');
assert.equal(await page.getByRole('button',{name:'关闭详情',exact:true}).count(),0);
await page.screenshot({path:`${out}/narrow.png`,fullPage:true});
results.push('540px detail preserves timeout evidence and Escape closes');
await page.evaluate(()=>{window.boardTimedSession=false;window.boardGoalStatus='paused'});
await page.getByRole('button',{name:'刷新状态',exact:true}).click();
await page.waitForSelector('[data-group="needs"] '+retry);
await page.waitForSelector('[data-group="done"] '+old);
results.push('paused shared Goal affects only current card');
assert.equal(await page.evaluate(()=>window.boardCalls.filter(c=>['run','rerun','status','archive'].includes(c.kind)).length),0);
assert.deepEqual(errors,[]);
await writeFile(`${out}/ui-results.json`,JSON.stringify({environment:'isolated actual React with synthetic read-only APIs',viewports:[1440,540],results,pageErrors:errors},null,2)+'\n');
console.log(JSON.stringify(results));await browser.close();
