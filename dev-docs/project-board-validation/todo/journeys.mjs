import {writeFile} from 'node:fs/promises';
import {resolve} from 'node:path';
export async function runJourneys(page,out) {
 await page.setViewportSize({width:1440,height:900});
 const results=[]; const errors=[]; page.on('pageerror',error=>errors.push(error.message));
 const progress={source:'live',todoSource:'tools',todoTotal:17,todoCompleted:3,todos:Array.from({length:17},(_,i)=>({key:'step-'+i,content:i===3?'完成薪资管理剩余实现':i===4?'执行完整测试与真实验收':i===5?'准备并执行生产发布':'核对业务规则与接口 '+(i+1),activeForm:i===3?'正在完成薪资管理剩余实现':'处理步骤 '+(i+1),status:i<3?'completed':i===3?'in_progress':'pending'})),agentTotal:3,agentRunning:2,agents:[{id:'review',agentType:'general-purpose',description:'审查薪资与个税规则',status:'running',background:true,startedAt:Date.now()-229000},{id:'verify',agentType:'local_bash',description:'验证个税同步',status:'running',background:true,startedAt:Date.now()-295000},{id:'test',agentType:'general-purpose',description:'接口回归结果',status:'failed',background:false,startedAt:Date.now()-300000,finishedAt:Date.now()-200000}]};
 await page.evaluate(p=>{window.boardWorkProgress=p;window.boardTimedSession=true},progress);
 await page.getByRole('button',{name:'刷新状态',exact:true}).click();
 const row=page.locator('[data-board-row="task:task-blocked"]').locator('..');
 await row.getByText('TODO 已完成 3/17',{exact:true}).waitFor();
 if(!await row.getByText('当前步骤：正在完成薪资管理剩余实现',{exact:true}).count())throw new Error('current step missing');
 await row.scrollIntoViewIfNeeded();
 await page.screenshot({path:resolve(out,'todo-card-dark-1440.png')});
 await row.locator('.pb-card-main').click();
 const detail=page.locator('.pb-detail');
 await detail.locator('.pb-progress-todos li').last().waitFor();
 if(await detail.locator('.pb-progress-todos li').count()!==17)throw new Error('plan count');
 if(await detail.locator('[data-todo-status="completed"]').count()!==3)throw new Error('completed count');
 if(await detail.locator('[data-agent-status="running"]').count()!==2)throw new Error('running child count');
 if(await detail.locator('[data-agent-status="failed"]').count()!==1)throw new Error('child failure lost');
 await page.screenshot({path:resolve(out,'todo-dark-1440.png')});results.push('card progress / detail 17 todos / 3 agents with failure');
 // Exact navigation remains independent from detail and progress is read-only.
 await detail.getByRole('button',{name:/任务一：研发 Agent Alpha/}).click();
 const call=await page.evaluate(()=>window.boardCalls.filter(c=>c.kind==='openSession').at(-1));
 if(call.sessionId!=='alpha-1')throw new Error('wrong original Session');
 await page.getByRole('button',{name:'项目看板',exact:true}).click();
 await detail.getByText('TODO 已完成 3/17',{exact:true}).waitFor();results.push('return retains selected detail and original Session navigation');
 await page.setViewportSize({width:540,height:900});
 await page.locator('[data-global-sidebar-mode="rail"]').waitFor();
 await page.mouse.move(530,850);
 await page.waitForFunction(()=>document.querySelector('.global-sidebar')?.getBoundingClientRect().width < 100);
 await page.evaluate(()=>Promise.all(document.getAnimations().filter(animation=>animation.effect?.getTiming().iterations!==Infinity).map(animation=>animation.finished.catch(()=>{}))));
 await detail.locator('.pb-progress-heading').first().waitFor();
 await detail.locator('.pb-progress-heading').first().scrollIntoViewIfNeeded();
 await page.screenshot({path:resolve(out,'todo-dark-540.png')});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw new Error('window horizontal overflow');
 await detail.getByRole('button',{name:'关闭详情'}).click();
 await page.getByRole('button',{name:'列表',exact:true}).click();
 const tableRow=page.getByRole('row').filter({has:page.getByRole('button',{name:'员工绩效回显异常',exact:true})});
 await tableRow.getByText('TODO 已完成 3/17',{exact:true}).waitFor();
 results.push('540 detail / list progress remains visible without overflow');
 await page.setViewportSize({width:1440,height:900});
 await page.evaluate(()=>{window.boardWorkProgress={...window.boardWorkProgress,todos:window.boardWorkProgress.todos.map(t=>({...t,status:'completed'})),todoCompleted:17}});
 await page.getByRole('button',{name:'刷新状态',exact:true}).click();await tableRow.getByText('TODO 已完成 17/17',{exact:true}).waitFor();
 if(!await tableRow.getByText('等待答复或授权',{exact:true}).count())throw new Error('TODO completion changed Task status');
 results.push('all TODO complete does not complete root Task');
 // Observation failure retains the previous plan; a stale snapshot must not look live.
 await page.clock.install({time:Date.now()});
 await page.evaluate(()=>window.boardFailObservation=true);
 await page.clock.runFor(61000);
 await tableRow.getByText('上次查询快照',{exact:true}).waitFor();
 await tableRow.getByRole('button',{name:'员工绩效回显异常',exact:true}).click();
 await page.locator('.pb-detail [data-agent-status="lastRunning"]').first().waitFor();
 await page.screenshot({path:resolve(out,'todo-stale-1440.png')});results.push('failed observation preserves plan and labels stale child state');
 await page.goto(page.url().split('?')[0]+'?light');
 await page.evaluate(p=>window.boardWorkProgress=p,progress);await page.getByRole('button',{name:'刷新状态',exact:true}).click();
 await page.getByRole('button',{name:'员工绩效回显异常 · 等待答复或授权'}).click();
 await page.locator('.pb-detail .pb-progress-todos li').last().waitFor();
 await page.screenshot({path:resolve(out,'todo-light-1440.png')});results.push('light theme plan and subagent detail');
 if(errors.length)throw new Error(errors.join('\n'));
 await writeFile(resolve(out,'todo-results.json'),JSON.stringify({kind:'actual React with synthetic isolated data, not native Provider acceptance',results,errors},null,2));
 console.log(JSON.stringify({todoJourneys:results,errors}));
}
