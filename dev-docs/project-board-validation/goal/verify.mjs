import assert from 'node:assert/strict';
import {writeFile} from 'node:fs/promises';
import {chromium} from 'playwright';
const out=import.meta.dirname;
const browser=await chromium.launch({headless:true,...(process.env.BOARD_BROWSER_EXECUTABLE ? {executablePath:process.env.BOARD_BROWSER_EXECUTABLE} : {})});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',error=>errors.push(error.message));
await page.goto('http://127.0.0.1:8886/__board_goal');
const selector='[data-board-row="task:task-done"]';
async function expectGroup(group){await page.waitForSelector(`[data-group="${group}"] ${selector}`)}
await expectGroup('running');
await page.screenshot({path:`${out}/running.png`,fullPage:true});
const results=['done Task + idle turn + active Goal renders in running'];
await page.getByRole('button',{name:'列表',exact:true}).click();
assert.match(await page.locator('tr').filter({hasText:'检查薪资前端构建及新测试服务器状态（合成）'}).innerText(),/正在执行/);
results.push('list view reports running');
await page.getByRole('button',{name:'看板',exact:true}).click();
await page.evaluate(()=>{window.boardGoalStatus='paused'});await page.getByRole('button',{name:'刷新状态',exact:true}).click();
await expectGroup('needs');await page.getByText('Goal 已暂停',{exact:true}).waitFor();results.push('paused Goal moves to confirmation with explicit paused badge');
await page.evaluate(()=>{window.boardGoalStatus='complete'});await page.getByRole('button',{name:'刷新状态',exact:true}).click();await expectGroup('done');results.push('completed Goal and done Task returns to done');
await page.evaluate(()=>{window.boardGoalStatus='active'});
await page.locator('[data-group="done"] article').getByRole('button',{name:'归档',exact:true}).click();
await page.getByRole('alert').waitFor();assert.equal(await page.evaluate(()=>window.boardCalls.filter(c=>c.kind==='archive').length),0);results.push('fresh Goal recheck rejects archive during idle turn');
await page.evaluate(()=>{window.boardGoalError=true});await page.getByRole('button',{name:'刷新状态',exact:true}).click();await expectGroup('needs');results.push('Goal lookup failure cannot leave the Task completed');
await page.evaluate(()=>{window.boardGoalError=false;window.boardGoalStatus='active'});await page.getByRole('button',{name:'刷新状态',exact:true}).click();await expectGroup('running');
await page.setViewportSize({width:540,height:900});await page.locator(selector).click();await page.getByRole('button',{name:'关闭详情',exact:true}).waitFor();await page.keyboard.press('Escape');
assert.equal(await page.getByRole('button',{name:'关闭详情',exact:true}).count(),0);results.push('540px detail opens and Escape closes');
await page.screenshot({path:`${out}/narrow.png`,fullPage:true});
assert.deepEqual(errors,[]);
await writeFile(`${out}/ui-results.json`,JSON.stringify({environment:'isolated synthetic React + mocked read-only APIs',viewports:[1440,540],results,pageErrors:errors},null,2)+'\n');
console.log(JSON.stringify(results));await browser.close();
