function managedCodexPlatform(): string | null {
  if (process.platform === 'darwin') {
    if (process.arch === 'arm64') return 'darwin-arm64';
    if (process.arch === 'x64') return 'darwin-x64';
    return null;
  }
  if (process.platform === 'win32') {
    if (process.arch === 'x64') return 'win32-x64';
    return null;
  }
  return null;
}

export function getManagedCodexHome(): string {
  return join(homedir(), APP_DATA_DIR_NAME, 'codex');
}

function getMyAgentsCliExecutablePath(): string {
  return join(homedir(), APP_DATA_DIR_NAME, 'bin', process.platform === 'win32' ? `${APP_CLI_NAME}.cmd` : APP_CLI_NAME);
}

function codexRuleString(value: string): string {
  return JSON.stringify(value);
}

function codexPrefixRule(pattern: string[]): string {
  return `prefix_rule(pattern=[${pattern.map(codexRuleString).join(', ')}], decision="allow")`;
}

export function buildManagedCodexRulesContent(): string {
  const cliPath = getMyAgentsCliExecutablePath();
  const patterns: string[][] = [
    [APP_CLI_NAME],
     [ `${APP_CLI_NAME}.cmd` ],
    [cliPath],
    ['/bin/zsh', '-lc', APP_CLI_NAME],
    ['/bin/zsh', '-lc', cliPath],
    ['/bin/bash', '-lc', APP_CLI_NAME],
    ['/bin/bash', '-lc', cliPath],
    ['zsh', '-lc', APP_CLI_NAME],
    ['bash', '-lc', APP_CLI_NAME],
    ['cmd.exe', '/d', '/s', '/c', APP_CLI_NAME],
    ['powershell', '-Command', APP_CLI_NAME],
    ['pwsh', '-Command', APP_CLI_NAME],
  ];
  return [
    '# Generated by MyAgents. Do not edit; it is refreshed when managed Codex starts.',
    '# Allows the built-in MyAgents CLI control-plane tool to run without sandbox approval.',
    ...patterns.map(codexPrefixRule),
    '',
  ].join('\n');
}

export function ensureManagedCodexRules(): void {
  const rulesDir = join(getManagedCodexHome(), 'rules');
  ensureDirSync(rulesDir);
  const rulesPath = join(rulesDir, 'myagents.rules');
  const content = buildManagedCodexRulesContent();
  try {
    if (existsSync(rulesPath) && readFileSync(rulesPath, 'utf-8') === content) return;
  } catch {
    // Fall through and rewrite; a broken generated rules file should self-heal.
  }
  writeFileSync(rulesPath, content, 'utf-8');
}

export function getManagedCodexRuntimeRoot(): string {
  return join(homedir(), APP_DATA_DIR_NAME, 'runtimes', 'codex');
}

function managedCodexInstallDir(platform: string, version = MANAGED_CODEX_REQUIRED_RUNTIME.version): string {
  if (!isCanonicalManagedCodexRuntimeVersion(version)) {
    throw new Error(`Invalid Managed Codex installed version: ${String(version)}`);
  }
  const root = resolve(getManagedCodexRuntimeRoot());
  const installDir = resolve(root, version, platform);
  const rel = relative(root, installDir);
  if (!rel || rel === '..' || rel.startsWith(`..${process.platform === 'win32' ? '\\' : '/'}`) || isAbsolute(rel)) {
    throw new Error(`Managed Codex install directory escapes runtime root: ${installDir}`);
  }
  return installDir;
}

function managedCodexInstalledJsonPath(): string {
  return join(getManagedCodexRuntimeRoot(), 'installed.json');
}

function isExecutableFileWithinRuntime(path: string): boolean {
  try {
    if (!statSync(path).isFile() || lstatSync(path).isSymbolicLink()) return false;
    const realRoot = realpathSync(getManagedCodexRuntimeRoot());
    const realPath = realpathSync(path);
    const rel = relative(realRoot, realPath);
    return Boolean(rel)
      && rel !== '..'
      && !rel.startsWith(`..${process.platform === 'win32' ? '\\' : '/'}`)
      && !isAbsolute(rel);
  } catch {
    return false;
  }
}

function readManagedCodexInstalledJson(): ManagedCodexInstalledJson | null {
  try {
    return JSON.parse(readFileSync(managedCodexInstalledJsonPath(), 'utf8')) as ManagedCodexInstalledJson;
  } catch {
    return null;
  }
}

function safeManagedCodexRelativePath(raw: string | undefined): string | null {
  if (!raw || raw.includes('\0') || raw.includes('\\') || raw.startsWith('/')) return null;
  if (/^[a-zA-Z]:/.test(raw)) return null;
  const segments = raw.split('/');
  if (segments.length === 0 || segments.length > 64) return null;
  for (const segment of segments) {
    if (!segment || segment === '.' || segment === '..' || segment.includes(':')) return null;
    if (/[ .]$/.test(segment)) return null;
  }
  return join(...segments);
}

function safeManagedCodexInstalledRelativePath(raw: string | undefined): string | null {
  const normalized = safeManagedCodexRelativePath(raw);
  if (normalized) return normalized;
  if (process.platform !== 'win32' || !raw?.includes('\\')) return null;
  return safeManagedCodexRelativePath(raw.replace(/\\/g, '/'));
}

export function resolveManagedCodexCommandPath(): string {
  return resolveManagedCodexInstallation().commandPath;
}

function hasVerifiedManagedCodexMetadata(
  installed: ManagedCodexInstalledJson,
  platform: string,
): boolean {
  if (!installed.manifestSignature?.trim() || installed.artifactSignatureVerified !== true) {
    return false;
  }
  const signing = installed.platformSignature;
  if (platform.startsWith('darwin-')) {
    return signing?.type === 'codesign' && Boolean(signing.teamId?.trim());
  }
  if (platform === 'win32-x64') {
    return signing?.type === 'authenticode'
      && /^[0-9a-f]{64}$/i.test(signing.certificateSha256 ?? '');
  }
  return false;
}

function managedCodexBinaryCandidates(installDir: string): string[] {
  return process.platform === 'win32'
    ? [
        join(installDir, 'codex.exe'),
        join(installDir, 'codex.cmd'),
        join(installDir, 'bin', 'codex.exe'),
        join(installDir, 'bin', 'codex.cmd'),
      ]
    : [
        join(installDir, 'codex'),
        join(installDir, 'bin', 'codex'),
      ];
}

function resolveManagedCodexInstallation(): { commandPath: string; version: string } {
  const platform = managedCodexPlatform();
  if (!platform) {
    throw new Error(`Managed Codex is not supported on ${process.platform}-${process.arch}`);
  }

  const installed = readManagedCodexInstalledJson();
  const installedVersion = installed?.version;
  const canUseInstalledVersion = isCanonicalManagedCodexRuntimeVersion(installedVersion)
    && installed?.platform === platform
    && hasVerifiedManagedCodexMetadata(installed, platform);
  if (canUseInstalledVersion) {
    const installDir = managedCodexInstallDir(platform, installedVersion);
    const rel = safeManagedCodexInstalledRelativePath(installed.executableRelativePath);
    if (rel) {
      const commandPath = join(installDir, rel);
      if (isExecutableFileWithinRuntime(commandPath)) return { commandPath, version: installedVersion };
    }
    const commandPath = managedCodexBinaryCandidates(installDir).find(isExecutableFileWithinRuntime);
    if (commandPath) return { commandPath, version: installedVersion };
  }
  throw new Error(
    `Managed Codex runtime is not installed with verified metadata for ${platform}`,
  );
}

function looksLikeAuthEnvName(name: string): boolean {
  const upper = name.toUpperCase();
  if (AUTH_ENV_NAMES.has(upper)) return true;
  if (AUTH_ENV_PREFIXES.some(prefix => upper.startsWith(prefix))) return true;
  return /(API|AUTH|ACCESS|REFRESH|BEARER).*?(KEY|TOKEN|SECRET|PASSWORD)/.test(upper)
    || /(KEY|TOKEN|SECRET|PASSWORD)$/.test(upper);
}

function buildManagedCodexEnv(
  policy?: RuntimeEnvPolicy,
): Record<string, string | undefined> {
  const base = augmentedProcessEnv(policy);
  const env: Record<string, string | undefined> = {};

  for (const key of MANAGED_SAFE_ENV_KEYS) {
    const value = base[key];
    if (value !== undefined) env[key] = value;
  }

  // Defense-in-depth: the allow-list above intentionally omits provider auth,
  // but keep an explicit scrub so future safe-key additions cannot accidentally
  // leak credentials into the managed Codex process.
  for (const key of Object.keys(env)) {
    if (key !== INTERNAL_CLI_TOKEN_ENV && looksLikeAuthEnvName(key)) delete env[key];
  }
  applyProviderProxyPolicyToEnv(env, CODEX_SUBSCRIPTION_PROVIDER_ID);

  const managedHome = getManagedCodexHome();
  ensureDirSync(managedHome);
  ensureDirSync(join(managedHome, 'logs'));
  ensureDirSync(join(managedHome, 'sessions'));
  ensureDirSync(join(managedHome, 'myagents'));
  ensureManagedCodexRules();

  env.CODEX_HOME = managedHome;
  env.HOME = env.HOME || homedir();
  if (process.platform === 'win32') {
    env.USERPROFILE = env.USERPROFILE || homedir();
    env.TEMP = env.TEMP || tmpdir();
    env.TMP = env.TMP || tmpdir();
  } else {
    env.TMPDIR = env.TMPDIR || tmpdir();
  }
  env.MYAGENTS_RUNTIME_SOURCE = 'managed-provider';
  return env;
}

export async function resolveCodexCommandContext(args: {
  source?: RuntimeSource;
  envPolicy?: RuntimeEnvPolicy;
} = {}): Promise<CodexCommandContext> {
  await ensureShellPath();
  const source = args.source ?? 'system-cli';
  if (source === 'managed-provider') {
    const platform = managedCodexPlatform();
    const installation = resolveManagedCodexInstallation();
    return {
      source,
      commandPath: installation.commandPath,
      env: buildManagedCodexEnv(args.envPolicy),
      codexHome: getManagedCodexHome(),
      version: installation.version,
      platform: platform ?? undefined,
    };
  }

  const env = augmentedProcessEnv(args.envPolicy);
  return {
    source: 'system-cli',
    commandPath: resolveCommand('codex', env),
    env,
  };
}

export function isManagedCodexRuntimeInstalled(): boolean {
  if (!existsSync(getManagedCodexRuntimeRoot())) return false;
  try {
    resolveManagedCodexCommandPath();
    return true;
  } catch {
    return false;
  }
}
